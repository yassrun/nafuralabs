import { createRequire } from 'node:module';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { createServer } from 'node:http';
import assert from 'node:assert/strict';

const require = createRequire(new URL('../../sources/web/package.json', import.meta.url));
const { chromium } = require('@playwright/test');
const folder = fileURLToPath(new URL('.', import.meta.url));
const html = await readFile(new URL('prototype.html', import.meta.url));
const server = createServer((req, res) => {
  res.writeHead(200, { 'Content-Type': 'text/html; charset=utf-8' });
  res.end(html);
});
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
const browser = await chromium.launch({ headless: true, channel: 'msedge' });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1 });
const errors = [];
const checks = [];
page.on('pageerror', error => errors.push(error.message));
const check = (name, condition) => { assert.ok(condition, name); checks.push(name); };
const tab = name => page.getByRole('tab', { name, exact: true }).click();
const close = () => page.getByRole('button', { name: 'Fermer', exact: true }).first().click();
try {
  await mkdir(new URL('previews/', import.meta.url), { recursive: true });
  await page.goto(`http://127.0.0.1:${server.address().port}`);
  check('Initial execution view renders 9 rows', await page.locator('.gantt-row').count() === 9);
  await page.getByRole('button', { name: 'Affichage', exact: true }).click();
  await page.locator('#modal').getByLabel('Date de début', { exact: true }).uncheck();
  check('Display panel hides start date immediately', !(await page.locator('.gantt-head [data-column="begin"]').isVisible()));
  await page.locator('#modal').getByLabel('Responsable', { exact: true }).check();
  check('Display panel reveals optional owner column', await page.locator('.gantt-head [data-column="owner"]').isVisible());
  await page.locator('#modal').getByLabel('Chronologie Gantt', { exact: true }).uncheck();
  check('Table-only display hides timeline and arrows', !(await page.locator('.time-head').isVisible()) && !(await page.locator('.dependency-overlay').isVisible()));
  await page.locator('#modal').getByLabel('Activités terminées', { exact: true }).uncheck();
  check('Completed rows can be hidden without deletion', await page.locator('.gantt-row').count() === 6);
  await page.getByRole('button', { name: 'Enregistrer comme vue…' }).click();
  await page.locator('#view-name').fill('Mon tableau personnalisé');
  await page.getByRole('button', { name: 'Enregistrer localement', exact: true }).click();
  await page.getByRole('button', { name: 'Affichage', exact: true }).click();
  await page.getByRole('button', { name: 'Réinitialiser', exact: true }).click();
  await page.getByRole('button', { name: 'Terminé', exact: true }).click();
  check('Display reset restores all initial rows', await page.locator('.gantt-row').count() === 9);
  await page.getByLabel('Vues enregistrées').selectOption('0');
  check('Saved view restores column and timeline visibility', !(await page.locator('.time-head').isVisible()) && !(await page.locator('.gantt-head [data-column="begin"]').isVisible()));
  await page.getByRole('button', { name: 'Affichage', exact: true }).click();
  await page.screenshot({ path: folder + 'previews/affichage.png', fullPage: true, style: '.toast{visibility:hidden!important}' });
  await page.getByRole('button', { name: 'Réinitialiser', exact: true }).click();
  await page.getByRole('button', { name: 'Terminé', exact: true }).click();
  check('Start, finish, duration, predecessors and margin are visible columns', /DÉBUT[\s\S]*FIN[\s\S]*DURÉE[\s\S]*PRÉDÉCESSEURS[\s\S]*MARGE/.test(await page.locator('.gantt-head').innerText()));
  check('Concrete start and finish dates are displayed in the row', (await page.locator('[data-row="A05"]').innerText()).includes('21/09/26') && (await page.locator('[data-row="A05"]').innerText()).includes('23/09/26'));
  await page.waitForFunction(() => document.querySelectorAll('.dependency-overlay [data-edge]').length === 6);
  check('Logical network draws six arrows', await page.locator('.dependency-overlay [data-edge]').count() === 6);
  await page.locator('.display-controls').getByLabel('Liaisons logiques', { exact: true }).uncheck();
  check('Logical link display can be turned off', !(await page.locator('.dependency-overlay').isVisible()));
  await page.locator('.display-controls').getByLabel('Liaisons logiques', { exact: true }).check();
  await page.getByRole('button', { name: 'Prédécesseur A03 · DD +4 j de A04', exact: true }).click();
  check('Dependency detail explains relation and lag', await page.locator('#modal').getByText('Début → début + 4 j ouvrés', { exact: true }).isVisible());
  await close();
  await page.locator('.display-controls').getByLabel('Chemin critique', { exact: true }).check();
  check('Critical path highlights five remaining elements', await page.locator('.critical-on .critical-row').count() === 5);
  check('Critical display is explicitly labelled illustrative', await page.getByText(/Marges et chemin critique illustratifs, non calculés/).isVisible());
  await page.waitForFunction(() => document.querySelectorAll('.dependency-overlay path[data-edge][stroke="#b23d41"]').length === 4);
  check('Critical connections are highlighted too', await page.locator('.dependency-overlay path[data-edge][stroke="#b23d41"]').count() === 4);
  await page.screenshot({ path: folder + 'previews/chemin-critique.png', fullPage: true, style: '.toast{visibility:hidden!important}' });
  await page.locator('.display-controls').getByLabel('Chemin critique', { exact: true }).uncheck();
  await page.screenshot({ path: folder + 'previews/execution.png', fullPage: true, style: '.toast{visibility:hidden!important}' });
  await page.getByLabel('Rechercher une activité').fill('inexistant');
  check('Empty search state is distinct', await page.getByText('Aucun élément ne correspond aux filtres.').isVisible());
  await page.getByRole('button', { name: 'Effacer les filtres' }).click();
  await page.getByLabel('Filtrer par nature').selectOption('Travaux');
  check('Nature filter restricts rows', await page.locator('.gantt-row').count() === 4);
  check('Filtered-out predecessors remain declared', await page.locator('.filtered-network').isVisible());
  await page.getByRole('button', { name: 'Enregistrer la vue', exact: true }).click();
  await page.locator('#view-name').fill('Travaux de la réunion');
  await page.getByRole('button', { name: 'Enregistrer localement', exact: true }).click();
  await page.getByLabel('Filtrer par nature').selectOption('all');
  await page.getByLabel('Vues enregistrées').selectOption('1');
  check('Saved view restores filters', await page.locator('.gantt-row').count() === 4);
  await page.getByLabel('Filtrer par nature').selectOption('all');
  await page.getByLabel('Comparer à R02').uncheck();
  check('Reference toggle hides reference bars', !(await page.locator('.baseline').first().isVisible()));
  await page.getByLabel('Comparer à R02').check();

  await tab('Client');
  await page.getByLabel('Niveau de détail client').selectOption('milestones');
  check('Client milestone-only selection', await page.locator('.paper tbody tr').count() === 1);
  await page.getByLabel('Niveau de détail client').selectOption('detail');
  await page.getByRole('button', { name: 'Choisir les éléments' }).click();
  await page.locator('[data-client-id="A01"]').uncheck();
  await page.getByRole('button', { name: 'Actualiser l’aperçu' }).click();
  check('Client publication allows explicit element selection', await page.locator('.paper tbody tr').count() === 5);
  const beforePublication = await page.locator('.paper tbody').innerText();
  await page.getByRole('button', { name: 'Figer une publication' }).click();
  await page.getByRole('button', { name: 'Figer dans la maquette' }).click();
  check('Client publication is frozen and unapproved', await page.getByText('Version figée · aucune approbation enregistrée').isVisible());
  await page.screenshot({ path: folder + 'previews/client.png', fullPage: true, style: '.toast{visibility:hidden!important}' });
  await tab('Exécution');
  await page.locator('.task-cell [data-task="A05"]').click();
  await page.getByRole('button', { name: 'Simuler un décalage' }).click();
  await page.getByRole('button', { name: 'Appliquer à la maquette', exact: true }).click();
  check('Impact application requires a reason', await page.getByText('Précisez le motif de cette modification.').isVisible());
  await page.getByRole('button', { name: 'Annuler', exact: true }).click();
  check('Cancel keeps revision unchanged', (await page.locator('#revision-label').innerText()).endsWith('08'));
  await page.locator('.task-cell [data-task="A05"]').click();
  await page.getByRole('button', { name: 'Simuler un décalage' }).click();
  await page.locator('#revision-reason').fill('Disponibilité de la grue');
  await page.getByRole('button', { name: 'Appliquer à la maquette', exact: true }).click();
  check('Local simulation updates revision', (await page.locator('#revision-label').innerText()).endsWith('09'));
  await page.locator('.task-cell [data-task="J01"]').click();
  check('Milestone detail follows the current simulated forecast', await page.locator('#modal').getByText('06 octobre 2026', { exact: true }).isVisible());
  await close();
  await tab('Client');
  check('Published content remains identical after internal revision', await page.locator('.paper tbody').innerText() === beforePublication);

  await tab('Ma semaine');
  await page.getByRole('button', { name: 'Préparer la semaine' }).click();
  check('Weekly picker only offers existing activities', await page.locator('#slot-activity option').count() === 2);
  await page.locator('#slot-activity').selectOption('A03');
  await page.getByRole('button', { name: 'Ajouter le créneau' }).click();
  check('Weekly slot outside activity window rejected', await page.getByText(/Ce créneau dépasse la fin prévue/).isVisible());
  await page.locator('#slot-activity').selectOption('A04');
  await page.getByRole('button', { name: 'Ajouter le créneau' }).click();
  check('Weekly slot added with same activity id', await page.locator('.slot[data-task="A04"]').count() === 3);
  await page.screenshot({ path: folder + 'previews/semaine.png', fullPage: true, style: '.toast{visibility:hidden!important}' });
  await page.getByRole('button', { name: 'Calendrier chantier' }).click();
  await page.getByRole('checkbox', { name: 'Samedi travaillé', exact: true }).check();
  await page.getByRole('button', { name: 'Appliquer à la maquette', exact: true }).click();
  check('Calendar changes Saturday opening', await page.locator('.day.closed').count() === 1);
  await page.getByRole('button', { name: 'Soumettre au conducteur' }).click();
  check('Submitted week has explicit status', await page.getByText('Soumise', { exact: true }).isVisible());
  await page.getByRole('button', { name: 'Reprendre en correction' }).click();
  check('Submitted week can return to local correction', await page.getByText('Brouillon', { exact: true }).isVisible());

  await tab('Financier');
  check('Partial payment balance visible', await page.getByRole('cell', { name: '360 000 MAD', exact: true }).isVisible());
  await page.getByRole('button', { name: 'Situation n° 03 · encaissement' }).click();
  check('Financial source detail opens', await page.getByRole('heading', { name: 'Situation n° 03 · suivi du paiement' }).isVisible());
  await close();
  await tab('Ressources');
  await page.getByRole('button', { name: 'Arbitrer' }).click();
  check('Resource conflict detail visible', await page.getByRole('heading', { name: 'Grue G-02 · réservation concurrente' }).isVisible());
  await page.keyboard.press('Escape');
  check('Escape closes modal', !(await page.locator('#modal').isVisible()));
  await tab('Synthèse');
  check('Summary reflects simulation', await page.getByText('06 octobre 2026', { exact: true }).isVisible());

  for (const width of [1024, 390]) {
    await page.setViewportSize({ width, height: 900 });
    for (const name of ['Synthèse', 'Exécution', 'Ma semaine', 'Client', 'Financier', 'Ressources']) {
      await tab(name);
      check(`${name}: no page overflow at ${width}px`, await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    }
  }
  await tab('Ma semaine');
  await page.screenshot({ path: folder + 'previews/mobile-semaine.png', fullPage: true, style: '.toast{visibility:hidden!important}' });
  check('No browser runtime errors', errors.length === 0);
  await writeFile(new URL('previews/verification.json', import.meta.url), JSON.stringify({ checkedAt: new Date().toISOString(), scope: 'Prototype only; not the Sektor application or scheduling engine', passed: checks.length, checks, errors }, null, 2));
  console.log(JSON.stringify({ passed: checks.length, errors, screenshots: ['execution.png','semaine.png','client.png','mobile-semaine.png'] }));
} finally {
  await browser.close();
  await new Promise(resolve => server.close(resolve));
}
